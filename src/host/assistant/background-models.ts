import {backgroundModel,backgroundModelKey,normalizeBackgroundModels,type BackgroundModel} from '../../shared/background-models.js'
import {loadWorkbenchState,workbenchGenerationGuard} from '../storage/state-store.js'

const service=(ctx:any,key:string)=>ctx?.get?.(key)||ctx?.[key]
const unavailable=(message:string)=>Object.assign(new Error(message),{code:'WORKBENCH_MODEL_UNAVAILABLE'})
/** Public Agent-scoped waterfalls, never SessionController.selectModel (which saves a global default). */
export function installBackgroundModelRoute(agent:any,route:BackgroundModel):()=>void{
 const scoped=agent?.ctx
 if(typeof scoped?.on!=='function')throw unavailable('当前宿主不支持独立后台模型，已保留原会话与任务进度')
 const disposers:Array<()=>void>=[]
 try{
  disposers.push(scoped.on('system-prompt/assemble',async(_assembly:any,_context:any,next:any)=>{const value=await next();return {...value,variables:{...value.variables,provider:route.provider,model:route.model}}},{prepend:true}))
  disposers.push(scoped.on('agent/request',async(_payload:any,next:any)=>{
   const value=await next(),{reasoningEffort:_inherited,...rest}=value
   // The selected model supplies its own reasoning default, rather than inheriting another model's effort.
   return {...rest,provider:route.provider,model:route.model}
  },{prepend:true}))
  disposers.push(scoped.on('agent/pre-step',async({agent:current,messages,signal,step}:any,next:any)=>{
   const decision=await next()
   if(decision.kind==='reject'||signal.aborted||decision.messages.length===0&&(step===1||messages.length>0))return decision
   const kept=decision.messages.filter((message:any)=>message.source?.kind!=='model-selection'),previous=current.session.requestHeader?.()?.config
   if(previous&&(previous.provider!==route.provider||previous.model!==route.model)){
    const from=previous.provider+'/'+previous.model,to=route.provider+'/'+route.model,text=`[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`
    kept.push(Object.freeze({id:randomUUID(),role:'user',content:Object.freeze([Object.freeze({type:'text',text})]),source:Object.freeze({kind:'model-selection',form:'notice',summary:from+' → '+to})}))
   }
   return {...decision,messages:kept}
  },{prepend:true}))
 }catch(error){for(const dispose of disposers)dispose();throw error}
 return ()=>{for(const dispose of disposers)dispose()}
}
type Binding={dispose:()=>void;key:string}
const bindings=new WeakMap<object,Binding>(),owners=new WeakMap<object,Map<string,()=>void>>()
/** Called immediately before prompt admission. The immutable route stays fixed for every step of that turn. */
export async function prepareBackgroundModel(ctx:any,sessionId:string,purpose:string):Promise<string>{
 if(purpose!=='analysis'&&purpose!=='summary')return ''
 const guard=workbenchGenerationGuard(),state=loadWorkbenchState()
 const thread=Object.values(state.backgroundThreads||{}).find((row:any)=>row.sessionId===sessionId) as any
 // A branch owns its model for the whole batch, including bounded repair turns.
 const route=thread?backgroundModel(thread.model):normalizeBackgroundModels(state.settings?.backgroundModels)[purpose]
 const controller=service(ctx,'sessionController')
 if(!route&&!owners.get(ctx)?.has(sessionId))return ''
 if(typeof controller?.resolveAgent!=='function')throw unavailable('当前宿主无法独立设置后台会话模型，已保留任务等待重试')
 const found=await controller.resolveAgent(sessionId);guard()
 if(found?.error)throw found.error
 const agent=found?.agent
 if(agent?.session?.id!==sessionId)throw unavailable('后台模型绑定的会话已变化，未提交任务')
 if(agent.status==='running')throw unavailable('后台会话仍在执行，本轮保留等待，模型在下一轮生效')
 const previous=bindings.get(agent),key=backgroundModelKey(route)
 if(previous?.key===key)return key
 if(route)await validateBackgroundModel(ctx,route);guard()
 previous?.dispose();owners.get(ctx)?.get(sessionId)?.();bindings.delete(agent)
 if(!route)return ''
 const remove=installBackgroundModelRoute(agent,route)
 const dispose=()=>{remove();bindings.delete(agent);if(owners.get(ctx)?.get(sessionId)===dispose)owners.get(ctx)?.delete(sessionId)}
 bindings.set(agent,{key,dispose})
 if(!owners.has(ctx)){
  const owned=new Map<string,()=>void>();owners.set(ctx,owned)
  ctx.effect?.(()=>()=>{for(const cleanup of [...owned.values()])cleanup();owners.delete(ctx)})
 }
 owners.get(ctx)!.set(sessionId,dispose)
 return key
}
/** Read native routing metadata only. Resolving configuration does not submit an inference request. */
export async function validateBackgroundModel(ctx:any,route:BackgroundModel):Promise<void>{
 const llm=service(ctx,'llm')
 if(typeof llm?.resolveCallConfig!=='function')throw unavailable('宿主未提供模型配置校验，请更新或重连宿主')
 let resolved:any
 try{resolved=await llm.resolveCallConfig(route)}catch{throw unavailable('所选模型配置不可用，请在 Harness 模型设置中检查服务商与凭据')}
 if(resolved?.provider!==route.provider||resolved?.model!==route.model)throw unavailable('宿主返回的模型与所选模型不一致，配置未应用')
}
export async function backgroundModelCatalog(ctx:any):Promise<any>{
 const controller=service(ctx,'sessionController')
 if(typeof controller?.modelCatalog!=='function')return {available:false,groups:[],note:'当前宿主不支持读取模型列表'}
 const raw=await controller.modelCatalog()
 // Return names and identities only, never connection settings or credentials.
 return {available:typeof controller.resolveAgent==='function'&&typeof service(ctx,'llm')?.resolveCallConfig==='function',groups:(Array.isArray(raw?.groups)?raw.groups:[]).map((group:any)=>({id:group.id,name:typeof group.name==='string'?group.name:group.id,models:(Array.isArray(group.models)?group.models:[]).map((model:any)=>({id:model.id,name:typeof model.name==='string'?model.name:model.id})).filter((model:any)=>backgroundModel({provider:group.id,model:model.id}))})).filter((group:any)=>group.models.length),failedProviders:(Array.isArray(raw?.failures)?raw.failures:[]).map((row:any)=>({id:row.provider||row.id,note:'该服务商模型列表暂不可用'}))}
}

/**
 * build.mjs — assembles the two shipped halves of dsh-dev-workbench.
 *
 * The plugin ships as two plain-JavaScript artifacts with no bundler and no
 * build-time dependency:
 *
 *   index.js  <- src/host/*.js   concatenated in filename order, then wrapped
 *                                  in nothing (each module is plain ESM at
 *                                  module scope; `src/host/90-apply.js` owns
 *                                  the `export function apply`).
 *   client.js <- src/client/*.js concatenated in filename order, then wrapped
 *                                  in the Harness browser module-loader factory
 *                                  whose id equals the package name.
 *
 * Concatenation (not module resolution) is deliberate: the browser half has
 * exactly one module-table import (`react`), and the Host half is loaded by
 * the Cordis loader as a single ESM entry. Both halves share one flat scope
 * per artifact, so authors must not redeclare top-level names across files of
 * the same half. `node scripts/build.mjs --check` fails on such a collision.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')

const PKG = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const NAME = PKG.name

function parts(dir) {
  const abs = join(root, dir)
  return readdirSync(abs)
    .filter((file) => file.endsWith('.js'))
    .sort()
    .map((file) => ({ file, path: join(abs, file), source: readFileSync(join(abs, file), 'utf8') }))
}

const problems = []

function collect(rootName, list) {
  const declared = new Map()
  for (const part of list) {
    const re = /^(?:export\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm
    let match
    while ((match = re.exec(part.source)) !== null) {
      const name = match[1]
      const seen = declared.get(name)
      if (seen && seen !== part.file) {
        problems.push(`${rootName}: '${name}' declared in both ${seen} and ${part.file}`)
      } else {
        declared.set(name, part.file)
      }
    }
  }
}

const hostParts = parts('src/host')
const clientParts = parts('src/client')
collect('host', hostParts)
collect('client', clientParts)

if (problems.length > 0) {
  console.error('build: top-level name collisions across concatenated parts:')
  for (const line of problems) console.error('  - ' + line)
  if (checkOnly) process.exit(1)
}

const banner = (half, list) =>
  [
    '/**',
    ` * ${NAME} — ${half} half (generated by scripts/build.mjs; do not edit by hand).`,
    ' *',
    ' * Source order:',
    ...list.map((part) => ` *   ${part.file}`),
    ' */',
    '',
  ].join('\n')

const host = [
  banner('Host', hostParts),
  ...hostParts.map((part) => `// ===== ${part.file} =====\n${part.source.trimEnd()}\n`),
].join('\n')

const client = [
  banner('Client', clientParts),
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(NAME)},`,
  '  factory(require) {',
  "    const React = require('react')",
  '',
  ...clientParts.map((part) => `    // ===== ${part.file} =====\n${indent(part.source.trimEnd(), 4)}\n`),
  '    return { name: ' + JSON.stringify(NAME) + ', inject: WB.inject, apply: WB.apply }',
  '  },',
  '})',
  '',
].join('\n')

function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? pad + line : line))
    .join('\n')
}

if (checkOnly) {
  console.log(`build --check: ${hostParts.length} host part(s), ${clientParts.length} client part(s), no collisions`)
  process.exit(0)
}

writeFileSync(join(root, 'index.js'), host)
writeFileSync(join(root, 'client.js'), client)
console.log(
  `build: index.js (${hostParts.length} part(s), ${host.length} bytes), ` +
    `client.js (${clientParts.length} part(s), ${client.length} bytes)`,
)
